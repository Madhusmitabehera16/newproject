# Database
# PostgreSQL-ready configuration from environment variables with graceful fallback
# to SQLite if PostgreSQL is not yet running or configured.
DB_ENGINE = os.getenv('DB_ENGINE', '')
DB_NAME = os.getenv('DB_NAME', 'api_monitor')
DB_USER = os.getenv('DB_USER', 'postgres')
DB_PASSWORD = os.getenv('DB_PASSWORD', 'postgres')
DB_HOST = os.getenv('DB_HOST', 'localhost')
DB_PORT = os.getenv('DB_PORT', '5432')

def _can_connect_postgres(dbname, user, password, host, port):
    try:
        import psycopg2
        conn = psycopg2.connect(
            dbname=dbname,
            user=user,
            password=password,
            host=host,
            port=port,
            connect_timeout=2
        )
        conn.close()
        return True
    except Exception:
        return False

# Use PostgreSQL if credentials successfully connect, otherwise fallback gracefully to SQLite
# so the application starts correctly even before PostgreSQL credentials/database are configured.
FORCE_SQLITE = os.getenv('FORCE_SQLITE', 'False').lower() in ('true', '1')

if not FORCE_SQLITE and _can_connect_postgres(DB_NAME, DB_USER, DB_PASSWORD, DB_HOST, DB_PORT):
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': DB_NAME,
            'USER': DB_USER,
            'PASSWORD': DB_PASSWORD,
            'HOST': DB_HOST,
            'PORT': DB_PORT,
        }
    }
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }

